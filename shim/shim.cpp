// Contract: `overloads` has `count` types. Returns whether the intrinsic `id`
// can be declared with them: LLVM aborts otherwise.
extern "C" bool lyftar_intrinsic_overloads_match(uint32_t id,
                                                 const LLVMTypeRef *overloads,
                                                 size_t count) {
  require(overloads != nullptr || count == 0,
          "lyftar_intrinsic_overloads_match: null list");
  if (id == 0 || id >= Intrinsic::num_intrinsics) {
    return false;
  }
  const auto intrinsic = static_cast<Intrinsic::ID>(id);
  SmallVector<Intrinsic::IITDescriptor, 8> descriptors;
  const ArrayRef<Intrinsic::IITDescriptor> table = std::get<0>(
      Intrinsic::getIntrinsicInfoTableEntries(intrinsic, descriptors));
  // Each overload slot is counted from the table, so a wrong count is known
  // without building anything.
  unsigned slots = 0;
  for (const Intrinsic::IITDescriptor &descriptor : table) {
    if (descriptor.Kind == Intrinsic::IITDescriptor::Overloaded ||
        descriptor.Kind == Intrinsic::IITDescriptor::VecOfAnyPtrsToElt) {
      slots = std::max(slots, descriptor.getOverloadIndex() + 1);
    }
  }
  if (slots != count) {
    return false;
  }
  // LLVM derives the rest of the signature from each overload type by casts it
  // doesn't check, so each must be the kind the intrinsic says.
  for (const Intrinsic::IITDescriptor &descriptor : table) {
    if (descriptor.Kind != Intrinsic::IITDescriptor::Overloaded) {
      continue;
    }
    const unsigned index = descriptor.getOverloadIndex();
    require(index < count, "lyftar_intrinsic_overloads_match: bad table");
    const Type *type = unwrap(ArrayRef(overloads, count)[index]);
    const auto [vector_kind, element_kind] =
        descriptor.getOverloadConstraints();
    const bool is_vector = isa<VectorType>(type);
    if (vector_kind == Intrinsic::IITDescriptor::VC_Vector && !is_vector) {
      return false;
    }
    if (vector_kind == Intrinsic::IITDescriptor::VC_Scalar && is_vector) {
      return false;
    }
    const Type *scalar = type->getScalarType();
    switch (element_kind) {
    case Intrinsic::IITDescriptor::EC_Integer:
      if (!scalar->isIntegerTy()) {
        return false;
      }
      break;
    case Intrinsic::IITDescriptor::EC_Float:
      if (!scalar->isFloatingPointTy()) {
        return false;
      }
      break;
    case Intrinsic::IITDescriptor::EC_Pointer:
      if (!scalar->isPointerTy()) {
        return false;
      }
      break;
    default:
      break;
    }
  }
  return true;
}

// Contract: `allocation` is an `alloca` in a function in a module, and
// `size_in_bytes` points to room for one number. Writes its size and returns
// true when the size is known here.
extern "C" bool lyftar_allocation_size_in_bytes(LLVMValueRef allocation,
                                                uint64_t *size_in_bytes) {
  require(allocation != nullptr && isa<AllocaInst>(unwrap(allocation)) &&
              size_in_bytes != nullptr,
          "lyftar_allocation_size_in_bytes: bad argument");
  const auto *instruction = cast<AllocaInst>(unwrap(allocation));
  auto size =
      instruction->getAllocationSize(instruction->getModule()->getDataLayout());
  if (!size || size->isScalable()) {
    return false;
  }
  *size_in_bytes = size->getFixedValue();
  return true;
}

