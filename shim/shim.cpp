// Contract: `parameters` has `count` types. Returns the index of the first
// parameter a function can't have, `count` if the return type is what's wrong,
// or UINT32_MAX if all are good.
extern "C" uint32_t lyftar_first_invalid_function_type_part(
    LLVMTypeRef return_type, const LLVMTypeRef *parameters, uint32_t count) {
  require(return_type != nullptr && (parameters != nullptr || count == 0),
          "lyftar_first_invalid_function_type_part: null argument");
  for (uint32_t index = 0; index < count; ++index) {
    if (!FunctionType::isValidArgumentType(
            unwrap(ArrayRef(parameters, count)[index]))) {
      return index;
    }
  }
  return FunctionType::isValidReturnType(unwrap(return_type)) ? AllGood : count;
}

// Contract: returns whether `checked` has a zero value LLVM can make without
// aborting.
extern "C" bool lyftar_type_has_null_value(LLVMTypeRef checked) {
  require(checked != nullptr, "lyftar_type_has_null_value: null type");
  const Type *type = unwrap(checked);
  if (const auto *target = dyn_cast<TargetExtType>(type)) {
    return target->hasProperty(TargetExtType::HasZeroInit);
  }
  return !type->isVoidTy() && !type->isFunctionTy() && !type->isLabelTy() &&
         !type->isMetadataTy() && !type->isX86_AMXTy();
}

// Contract: `name` is a C string, `type_parameters` has `type_parameter_count`
// types, and `integer_parameters` has `integer_parameter_count` numbers.
// Returns whether LLVM accepts them, since LLVM doesn't check them in a release
// build when asked for the type directly.
extern "C" bool lyftar_target_extension_type_is_valid(
    LLVMContextRef context, const char *name,
    const LLVMTypeRef *type_parameters, uint32_t type_parameter_count,
    const uint32_t *integer_parameters, uint32_t integer_parameter_count) {
  require(context != nullptr && name != nullptr &&
              (type_parameters != nullptr || type_parameter_count == 0) &&
              (integer_parameters != nullptr || integer_parameter_count == 0),
          "lyftar_target_extension_type_is_valid: bad argument");
  SmallVector<Type *, 4> types;
  for (uint32_t index = 0; index < type_parameter_count; ++index) {
    types.push_back(
        unwrap(ArrayRef(type_parameters, type_parameter_count)[index]));
  }
  Expected<TargetExtType *> result = TargetExtType::getOrError(
      *unwrap(context), name, types,
      ArrayRef<unsigned>(integer_parameters, integer_parameter_count));
  if (!result) {
    consumeError(result.takeError());
    return false;
  }
  return true;
}

// Contract: returns whether a global can hold a value of type `checked`.
