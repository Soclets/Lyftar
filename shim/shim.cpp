  require(metadata != nullptr, "lyftar_metadata_is: null metadata");
  const Metadata *node = unwrap(metadata);
  switch (which) {
  case 0:
    return isa<DIFile>(node);
  case 1:
    return isa<DIScope>(node);
  case 2:
    return isa<DIType>(node);
  case 3:
    return isa<DILocalVariable>(node);
  case 4:
    return isa<DIExpression>(node);
  case 5:
    return isa<DILocation>(node);
  case 6:
    return isa<DISubprogram>(node);
  case 7:
    return isa<DILabel>(node);
  case 8:
    return isa<MDNode>(node);
  case 9:
    return isa<DIGlobalVariableExpression>(node);
  case 10:
    return isa<DIVariable>(node);
  case 11:
    return isa<DIMacroFile>(node);
  case 12:
    return isa<MDString>(node);
  case 13:
    return isa<DINode>(node);
  case 14:
    return isa<DILocalScope>(node);
  case 15:
    return isa<DIGlobalVariable>(node);
  default:
    return false;
  }
