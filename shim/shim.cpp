// Contract: `function_type` is a function type and `arguments` has `count`
// values. Returns UINT32_MAX if they fit, UINT32_MAX - 1 if there are the wrong
// number of them, and otherwise the index of the first with the wrong type.
// trace: D3
extern "C" uint32_t
lyftar_call_first_bad_argument(LLVMTypeRef function_type,
                               const LLVMValueRef *arguments, uint32_t count) {
  require(function_type != nullptr && (arguments != nullptr || count == 0),
          "lyftar_call_first_bad_argument: null argument");
  const auto *type = dyn_cast<FunctionType>(unwrap(function_type));
  require(type != nullptr,
          "lyftar_call_first_bad_argument: not a function type");
  const uint32_t parameters = type->getNumParams();
  if (count < parameters || (count > parameters && !type->isVarArg())) {
    return AllGood - 1;
  }
  for (uint32_t index = 0; index < parameters; ++index) {
    if (type->getParamType(index) !=
        unwrap(ArrayRef(arguments, count)[index])->getType()) {
      return index;
    }
  }
  return AllGood;
}

// Contract: returns whether `atomicrmw` of `operation` takes a value of type
// `value_type`.
extern "C" bool
lyftar_atomic_read_modify_write_is_valid(LLVMAtomicRMWBinOp operation,
                                         LLVMTypeRef value_type) {
  require(value_type != nullptr,
          "lyftar_atomic_read_modify_write_is_valid: null type");
  const Type *type = unwrap(value_type);
  switch (operation) {
  case LLVMAtomicRMWBinOpXchg:
    return type->isIntegerTy() || type->isFloatingPointTy() ||
           type->isPointerTy();
  case LLVMAtomicRMWBinOpFAdd:
  case LLVMAtomicRMWBinOpFSub:
  case LLVMAtomicRMWBinOpFMax:
  case LLVMAtomicRMWBinOpFMin:
  case LLVMAtomicRMWBinOpFMaximum:
  case LLVMAtomicRMWBinOpFMinimum:
  case LLVMAtomicRMWBinOpFMaximumNum:
  case LLVMAtomicRMWBinOpFMinimumNum:
    return type->isFloatingPointTy();
  default:
    return type->isIntegerTy();
  }
}

