// Contract: `values` has `count` distinct live values, each an instruction,
// block or global. Returns the first value that goes away and is still used by
// something that stays, or null. A constant user counts only if it stays in
// use: `removeDeadConstantUsers` clears the ones no one uses, and it runs first
// in `lyftar_erase_values`. A block address doesn't block a block, because LLVM
// rewrites it when the block goes, and a phi's entry for a block in the list
// goes with that block. trace: D11
extern "C" LLVMValueRef lyftar_erase_find_blocker(const LLVMValueRef *values,
                                                  size_t count) {
  require(values != nullptr || count == 0,
          "lyftar_erase_find_blocker: null list");
  const ArrayRef<LLVMValueRef> list(values, count);
  SmallPtrSet<const Value *, 32> going;
  collectGoing(list, &going);
  for (const Value *value : going) {
    for (const Use &use : value->uses()) {
      const User *user = use.getUser();
      if (going.contains(user) || isa<BlockAddress>(user)) {
        continue;
      }
      // A phi's entry for a block that goes, goes with that block.
      if (const auto *phi = dyn_cast<PHINode>(user);
          phi != nullptr && going.contains(phi->getIncomingBlock(use))) {
        continue;
      }
      // A global's initializer, an alias's target and a function's personality
      // are real uses, even when nothing uses that global. Only a constant
      // expression or aggregate that nothing uses can go.
      const auto *constant = dyn_cast<Constant>(user);
      if (constant == nullptr || isa<GlobalValue>(constant) ||
          constant->isConstantUsed()) {
        return wrap(value);
      }
    }
  }
  return nullptr;
}

// Contract: `values` has `count` distinct live values for which
// `lyftar_erase_find_blocker` gave null, and the caller holds exclusive access
// to their module. Erases them all. A block's erasure drops it from the phis of
// its function, so no phi keeps a pointer to a block that's gone. trace: D11
extern "C" void lyftar_erase_values(const LLVMValueRef *values, size_t count) {
  require(values != nullptr || count == 0, "lyftar_erase_values: null list");
  const ArrayRef<LLVMValueRef> list(values, count);
  SmallVector<Instruction *, 16> instructions;
  SmallVector<BasicBlock *, 8> blocks;
  SmallVector<GlobalValue *, 8> globals;
  for (LLVMValueRef raw_value : list) {
    Value *value = unwrap(raw_value);
    if (auto *instruction = dyn_cast<Instruction>(value)) {
      instructions.push_back(instruction);
    } else if (auto *block = dyn_cast<BasicBlock>(value)) {
      blocks.push_back(block);
    } else {
      auto *global = dyn_cast<GlobalValue>(value);
      require(global != nullptr, "lyftar_erase_values: not erasable");
      globals.push_back(global);
    }
  }
  // Drop every reference first, so that items in the list can use each other in
  // any order.
  for (Instruction *instruction : instructions) {
    instruction->dropAllReferences();
  }
  for (BasicBlock *block : blocks) {
    block->dropAllReferences();
  }
  for (GlobalValue *global : globals) {
    if (auto *function = dyn_cast<Function>(global)) {
      function->deleteBody();
    }
    global->removeDeadConstantUsers();
  }
  for (Instruction *instruction : instructions) {
    instruction->eraseFromParent();
  }
  for (BasicBlock *block : blocks) {
    Function *parent = block->getParent();
    for (BasicBlock &other : *parent) {
      if (&other == block) {
        continue;
      }
      for (PHINode &phi : other.phis()) {
        for (int index = phi.getBasicBlockIndex(block); index >= 0;
             index = phi.getBasicBlockIndex(block)) {
          phi.removeIncomingValue(static_cast<unsigned>(index), false);
        }
      }
    }
    block->eraseFromParent();
  }
  for (GlobalValue *global : globals) {
    global->eraseFromParent();
  }
}

